package release

import "testing"

func TestParse(t *testing.T) {
	tests := []struct {
		name string
		in   string
		want Info
	}{
		{
			// The brackets scene releases wrap their tags in used to survive
			// tokenization, so "[1080p]" and "[WEBRip]" were taken as part of
			// the title and "(2026)" hid the release year.
			name: "bracketed tags and parenthesized year",
			in:   "The End Of Oak Street (2026) [1080p] [WEBRip] [5.1] [YTS.GG - YTS.BZ]",
			want: Info{Kind: KindMovie, Title: "The End Of Oak Street", Year: 2026},
		},
		{
			name: "parenthesized year without brackets",
			in:   "The End Of Oak Street (2026) 1080p WEBRip 5.1 YTS.GG",
			want: Info{Kind: KindMovie, Title: "The End Of Oak Street", Year: 2026},
		},
		{
			name: "dotted movie name",
			in:   "Movie.Title.2023.1080p.BluRay.x264",
			want: Info{Kind: KindMovie, Title: "Movie Title", Year: 2023},
		},
		{
			name: "year in title is not the release year",
			in:   "Blade Runner 2049 2017 1080p BluRay",
			want: Info{Kind: KindMovie, Title: "Blade Runner 2049", Year: 2017},
		},
		{
			name: "single episode",
			in:   "Some.Show.S02E03.1080p.WEB-DL",
			want: Info{Kind: KindEpisode, Title: "Some Show", Season: 2, Episode: 3},
		},
		{
			name: "season pack",
			in:   "Some.Show.S02.1080p.WEB-DL",
			want: Info{Kind: KindSeason, Title: "Some Show", Season: 2},
		},
		{
			// A show name is often followed by its first-air year; the year is
			// not part of the name and must not be sent to TMDB.
			name: "year after show name is dropped",
			in:   "Lanterns.2026.S01E02.1080p.x265-ELiTE",
			want: Info{Kind: KindEpisode, Title: "Lanterns", Season: 1, Episode: 2},
		},
		{
			name: "year-only show name is kept",
			in:   "1923.S01E01.1080p.x265-ELiTE",
			want: Info{Kind: KindEpisode, Title: "1923", Season: 1, Episode: 1},
		},
		{
			name: "episode title is kept",
			in:   "Silo.S03E09.Farewell.1080p.ATVP.WEB-DL",
			want: Info{Kind: KindEpisode, Title: "Silo", Season: 3, Episode: 9, EpisodeTitle: "Farewell"},
		},
		{
			// Language tags sit where an episode title would, but are not one.
			name: "language tags are not an episode title",
			in:   "Lanterns.S01E03.ITA.ENG.2160p.AMZN.WEB-DL",
			want: Info{Kind: KindEpisode, Title: "Lanterns", Season: 1, Episode: 3},
		},
		{
			name: "hyphen before the episode marker",
			in:   "Lioness.2023-S03E06.720p.x264-FENiX",
			want: Info{Kind: KindEpisode, Title: "Lioness", Season: 3, Episode: 6},
		},
		{
			// "Extended" is part of this title, not a release edition tag, so
			// the year after it must still be found.
			name: "edition word inside the title",
			in:   "Grand.Theft.Auto.VI.An.Extended.Look.2026.2160p.NF.WEB-DL.DDP5.1.H.265",
			want: Info{Kind: KindMovie, Title: "Grand Theft Auto VI An Extended Look", Year: 2026},
		},
		{
			// The season is spelled out and the show name carries its year.
			name: "spelled-out season pack",
			in:   "Prehistoric Planet (2022) Season 1 S01 (1080p ATVP WEB-DL x265 HEVC 10bit EAC3 5.1 Silence) [QxR]",
			want: Info{Kind: KindSeason, Title: "Prehistoric Planet", Season: 1},
		},
		{
			name: "spelled-out season without Sxx",
			in:   "Some Show Season 2 1080p WEB-DL",
			want: Info{Kind: KindSeason, Title: "Some Show", Season: 2},
		},
		{
			// "Season" here starts a movie title, not a season marker.
			name: "season word in a movie title",
			in:   "Season of the Witch 2011 1080p BluRay",
			want: Info{Kind: KindMovie, Title: "Season of the Witch", Year: 2011},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := Parse(tt.in); got != tt.want {
				t.Errorf("Parse(%q) = %+v, want %+v", tt.in, got, tt.want)
			}
		})
	}
}

